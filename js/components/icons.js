export const PAGE_ICON = { home: 'home', papers: 'papers', series: 'series', gallery: 'gallery', log: 'log', custom: 'custom' };

const cache = {};
function svgFor(name) {
  if (cache[name]) return cache[name];
  const rows = PIX[name] || PIX.leaf;
  let rects = '';
  rows.forEach((row, y) => [...row.slice(0, 12)].forEach((c, x) => {
    if (c === '#') rects += `<rect x="${x}" y="${y}" width="1" height="1"/>`;
  }));
  return (cache[name] = `<svg viewBox="0 0 12 12" fill="currentColor" shape-rendering="crispEdges">${rects}</svg>`);
}

/** 아이콘 요소 만들기 — icon('leaf') */
export function icon(name, cls = '') {
  const span = document.createElement('span');
  span.className = 'ico ' + cls;
  span.setAttribute('aria-hidden', 'true');
  span.innerHTML = svgFor(name);
  return span;
}
